(** * Sorted equality generated by guarded rules

    Equality closes client rules under equivalence and operator congruence.
    For example, a guarded equality can be used inside an application or in reverse.
    Builds on: RewriteSyntax, RewriteRules and Rocq Stdlib lists. *)

From Stdlib Require Import List.
From Gaulois.Rewrite Require Import RewriteSyntax RewriteRules.
Import List.ListNotations.

Scheme All for Forall2.

(** Equality admits only declared, guarded rule instances with checked substitutions. *)
Inductive rw_equal {K Sort V H C} (sig : rw_signature K Sort V)
    (admissible : rw_semantics K Sort V C -> Prop) (rules : list (rw_rule K Sort V H)) :
    rw_term K Sort V -> rw_term K Sort V -> Prop :=
  | rw_eq_refl : forall t, rw_equal sig admissible rules t t
  | rw_eq_sym : forall t u,
      rw_equal sig admissible rules t u -> rw_equal sig admissible rules u t
  | rw_eq_trans : forall t u v,
      rw_equal sig admissible rules t u ->
      rw_equal sig admissible rules u v -> rw_equal sig admissible rules t v
  | rw_eq_app : forall s op ts us,
      Forall2 (rw_equal sig admissible rules) ts us ->
      rw_equal sig admissible rules (RWApp s op ts) (RWApp s op us)
  | rw_eq_rule : forall r sub l u,
      In r rules -> rw_sub_typed sig (rw_hole_sort r) sub ->
      rw_condition r sub = true -> rw_instantiate sub (rw_lhs r) = Some l ->
      rw_instantiate sub (rw_rhs r) = Some u -> rw_equal sig admissible rules l u.

(** Nested induction retains hypotheses for each pair of congruent arguments. *)
Lemma rw_equal_ind_all {K Sort V H C} (sig : rw_signature K Sort V)
    (admissible : rw_semantics K Sort V C -> Prop) (rules : list (rw_rule K Sort V H))
    (P : rw_term K Sort V -> rw_term K Sort V -> Prop)
    (Hrefl : forall t, P t t)
    (Hsym : forall t u, rw_equal sig admissible rules t u -> P t u -> P u t)
    (Htrans : forall t u v, rw_equal sig admissible rules t u -> P t u ->
      rw_equal sig admissible rules u v -> P u v -> P t v)
    (Happ : forall s op ts us, Forall2 (rw_equal sig admissible rules) ts us ->
      Forall2 P ts us -> P (RWApp s op ts) (RWApp s op us))
    (Hrule : forall r sub l u, In r rules -> rw_sub_typed sig (rw_hole_sort r) sub ->
      rw_condition r sub = true -> rw_instantiate sub (rw_lhs r) = Some l ->
      rw_instantiate sub (rw_rhs r) = Some u -> P l u) :
  forall t u, rw_equal sig admissible rules t u -> P t u.
Proof.
  fix IH 3.
  intros t u Hequal.
  destruct Hequal as [t|t u Hequal|t u v Htu Huv|s op ts us Hargs|
    r sub l u Hin Hsub Hguard Hlhs Hrhs].
  - exact (Hrefl t).
  - exact (Hsym t u Hequal (IH t u Hequal)).
  - exact (Htrans t u v Htu (IH t u Htu) Huv (IH u v Huv)).
  - apply Happ; [exact Hargs|].
    induction Hargs as [|t u ts us Htu Hrest IHrest].
    + constructor.
    + constructor; [exact (IH t u Htu)|exact IHrest].
  - exact (Hrule r sub l u Hin Hsub Hguard Hlhs Hrhs).
Qed.

Lemma rw_denote_args_agrees {K Sort V C} (sem : rw_semantics K Sort V C)
    (ts us : list (rw_term K Sort V)) :
  Forall2 (fun t u => rw_denote sem t = rw_denote sem u) ts us ->
  rw_denote_args sem ts = rw_denote_args sem us.
Proof.
  intros Hargs.
  induction Hargs as [|t u ts us Htu Hrest IHrest].
  - reflexivity.
  - rewrite !rw_denote_args_cons.
    now rewrite Htu, IHrest.
Qed.

(** Sound client rules generate equality of complete option results, including undefined ones. *)
Theorem rw_equal_sound {K Sort V H C} (sig : rw_signature K Sort V)
    (admissible : rw_semantics K Sort V C -> Prop) (rules : list (rw_rule K Sort V H)) :
  Forall (rw_rule_sound sig admissible) rules ->
  forall t u, rw_equal sig admissible rules t u -> rw_equiv admissible t u.
Proof.
  intros Hrules.
  apply (rw_equal_ind_all sig admissible rules (rw_equiv admissible)).
  - intros t sem Hsem; reflexivity.
  - intros t u Hequal IH sem Hsem; symmetry; exact (IH sem Hsem).
  - intros t u v Htu IHtu Huv IHuv sem Hsem.
    transitivity (rw_denote sem u); [exact (IHtu sem Hsem)|exact (IHuv sem Hsem)].
  - intros s op ts us Hargs IHargs sem Hsem.
    rewrite !rw_denote_app.
    assert (Hdenotes : Forall2 (fun t u => rw_denote sem t = rw_denote sem u) ts us).
    { clear Hargs.
      induction IHargs as [|t u ts us Htu Hrest IHrest].
      - constructor.
      - constructor; [exact (Htu sem Hsem)|exact IHrest]. }
    now rewrite (rw_denote_args_agrees sem ts us Hdenotes).
  - intros r sub l u Hin Hsub Hguard Hlhs Hrhs.
    pose proof (proj1 (Forall_forall (rw_rule_sound sig admissible) rules) Hrules r Hin)
      as Hsound.
    exact (Hsound sub l u Hsub Hguard Hlhs Hrhs).
Qed.

(** * Type and sort preservation *)

Lemma rw_rule_instance_typed {K Sort V H} (sig : rw_signature K Sort V)
    (r : rw_rule K Sort V H) (sub : rw_substitution K Sort V H) l u :
  rw_rule_wf sig r -> rw_sub_typed sig (rw_hole_sort r) sub ->
  rw_instantiate sub (rw_lhs r) = Some l -> rw_instantiate sub (rw_rhs r) = Some u ->
  rw_typed sig l /\ rw_typed sig u /\ rw_sort l = rw_sort u.
Proof.
  intros [_ [_ [Hlhs [Hrhs Hsort]]]] Hsub Hinstl Hinstu.
  destruct (rw_instantiate_typed sig (rw_hole_sort r) sub (rw_lhs r) Hlhs Hsub)
    as [l' [Hinstl' [Htypedl Hsortl]]].
  destruct (rw_instantiate_typed sig (rw_hole_sort r) sub (rw_rhs r) Hrhs Hsub)
    as [u' [Hinstu' [Htypedu Hsortu]]].
  rewrite Hinstl in Hinstl'; injection Hinstl' as Hleft; subst l'.
  rewrite Hinstu in Hinstu'; injection Hinstu' as Hright; subst u'.
  split; [exact Htypedl|split; [exact Htypedu|now rewrite Hsortl, Hsortu]].
Qed.

Lemma rw_typed_app_inv {K Sort V} (sig : rw_signature K Sort V) s op args :
  rw_typed sig (RWApp s op args) ->
  Forall (rw_typed sig) args /\ rw_operator_shape sig op (map rw_sort args) s = true.
Proof.
  intros Htyped.
  inversion Htyped as [|s' op' args' Hargs Hshape]; subst.
  split; assumption.
Qed.

Lemma rw_args_typed_agrees {K Sort V} (sig : rw_signature K Sort V) ts us :
  Forall2 (fun t u => rw_sort t = rw_sort u /\ (rw_typed sig t <-> rw_typed sig u)) ts us ->
  map rw_sort ts = map rw_sort us /\
    (Forall (rw_typed sig) ts <-> Forall (rw_typed sig) us).
Proof.
  intros Hargs.
  induction Hargs as [|t u ts us [Hsort Htyped] Hrest [Hsorts Htypeds]].
  - split; [reflexivity|reflexivity].
  - split.
    + cbn; now rewrite Hsort, Hsorts.
    + rewrite !Forall_cons_iff; tauto.
Qed.

Lemma rw_app_typed_agrees {K Sort V} (sig : rw_signature K Sort V) s op ts us :
  Forall2 (fun t u => rw_sort t = rw_sort u /\ (rw_typed sig t <-> rw_typed sig u)) ts us ->
  rw_typed sig (RWApp s op ts) <-> rw_typed sig (RWApp s op us).
Proof.
  intros Hargs.
  destruct (rw_args_typed_agrees sig ts us Hargs) as [Hsorts Htypeds].
  split; intro Htyped; apply rw_typed_app.
  - apply Htypeds; exact (proj1 (rw_typed_app_inv sig s op ts Htyped)).
  - rewrite <- Hsorts; exact (proj2 (rw_typed_app_inv sig s op ts Htyped)).
  - apply Htypeds; exact (proj1 (rw_typed_app_inv sig s op us Htyped)).
  - rewrite Hsorts; exact (proj2 (rw_typed_app_inv sig s op us Htyped)).
Qed.

(** Bidirectional typing is the invariant needed to handle the symmetry constructor. *)
Lemma rw_equal_typed_agrees {K Sort V H C} (sig : rw_signature K Sort V)
    (admissible : rw_semantics K Sort V C -> Prop) (rules : list (rw_rule K Sort V H)) :
  Forall (rw_rule_wf sig) rules ->
  forall t u, rw_equal sig admissible rules t u ->
    rw_sort t = rw_sort u /\ (rw_typed sig t <-> rw_typed sig u).
Proof.
  intros Hrules.
  apply (rw_equal_ind_all sig admissible rules
    (fun t u => rw_sort t = rw_sort u /\ (rw_typed sig t <-> rw_typed sig u))).
  - intro t; split; reflexivity.
  - intros t u Hequal [Hsort Htyped]; split; [symmetry; exact Hsort|tauto].
  - intros t u v Htu [Hsorttu Htypedtu] Huv [Hsortuv Htypeduv].
    split; [now transitivity (rw_sort u)|tauto].
  - intros s op ts us Hargs IHargs.
    split; [reflexivity|exact (rw_app_typed_agrees sig s op ts us IHargs)].
  - intros r sub l u Hin Hsub Hguard Hlhs Hrhs.
    pose proof (proj1 (Forall_forall (rw_rule_wf sig) rules) Hrules r Hin) as Hwf.
    destruct (rw_rule_instance_typed sig r sub l u Hwf Hsub Hlhs Hrhs)
      as [Htypedl [Htypedu Hsort]].
    split; [exact Hsort|split; intro Htyped; assumption].
Qed.

(** Equality generated by well-formed rules preserves typing and the annotated result sort. *)
Theorem rw_equal_typed {K Sort V H C} (sig : rw_signature K Sort V)
    (admissible : rw_semantics K Sort V C -> Prop) (rules : list (rw_rule K Sort V H)) :
  Forall (rw_rule_wf sig) rules ->
  forall t u, rw_typed sig t -> rw_equal sig admissible rules t u ->
    rw_typed sig u /\ rw_sort t = rw_sort u.
Proof.
  intros Hrules t u Htyped Hequal.
  destruct (rw_equal_typed_agrees sig admissible rules Hrules t u Hequal)
    as [Hsort Htypeds].
  split; [now apply Htypeds|exact Hsort].
Qed.
