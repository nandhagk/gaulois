(** * Dense expression analyses and checked code motion

    Available and anticipated expressions share finite gen/kill transfers and must-facts.
    For example, inserting an expression on an empty branch can make its later deletion valid.
    Builds on: AnalysesLiveness, OrderPowerset, ViewsGraph and ViewsForward. *)

From Stdlib Require Import List Bool.
From Gaulois.Collections Require Import CollectionsEncoding CollectionsFinSet.
From Gaulois.Order Require Import OrderLattice OrderConcrete OrderPowerset.
From Gaulois.Graph Require Import GraphCore.
From Gaulois.Fixpoint Require Import FixpointSystem.
From Gaulois.Views Require Import ViewsSemantics ViewsGraph ViewsForward.
From Gaulois.Analyses Require Import AnalysesLiveness.
Import List.ListNotations.

(** The expression view describes generation, invalidation and current expression values. *)
Record genkill_view (S O N E U C : Type) : Type := GenKillView {
  gkview : graph_view S O N E;
  gen : E -> list U;
  kill : E -> U -> bool;
  uval : S -> U -> option C
}.

Arguments GenKillView {S O N E U C}.
Arguments gkview {S O N E U C}.
Arguments gen {S O N E U C}.
Arguments kill {S O N E U C}.
Arguments uval {S O N E U C}.

(** Generated and uninvalidated expressions keep their values across semantic steps. *)
Record genkill_laws {S O N E U C} (m : semantics S O) (en : endings S)
    (gk : genkill_view S O N E U C) : Prop := {
  gk_view : graph_view_laws m (gkview gk);
  gk_no_stays : forall s l s', ~ stays (gkview gk) s l s';
  gen_value : forall s l s' e u, reachable_state m s -> step m s l s' ->
    taken (gkview gk) s l s' e -> In u (gen gk e) -> uval gk s' u = uval gk s u;
  kill_frame : forall s l s' e u, reachable_state m s -> step m s l s' ->
    taken (gkview gk) s l s' e -> kill gk e u = false -> uval gk s' u = uval gk s u;
  final_exit : forall s, reachable_state m s -> final en s ->
    Graph.out (cfg (gkview gk)) (point (gkview gk) s) = nil
}.

Arguments gk_view {S O N E U C m en gk}.
Arguments gk_no_stays {S O N E U C m en gk}.
Arguments gen_value {S O N E U C m en gk}.
Arguments kill_frame {S O N E U C m en gk}.
Arguments final_exit {S O N E U C m en gk}.

(** The expression universe contains precisely the expressions generated by graph edges. *)
Definition expr_universe {S O N E U C} (EU : encoding U) (gk : genkill_view S O N E U C) :
    list U :=
  FinSet.elements (FinSet.of_list EU (flat_map (gen gk) (edges_of (cfg (gkview gk))))).

(** Available facts carry support in the finite expression universe. *)
Definition avail_set {S O N E U C} (EU : encoding U) (gk : genkill_view S O N E U C) : Type :=
  finite_set EU (expr_universe EU gk).

(** Must-facts join by intersection and start from the whole universe. *)
Definition avail_lattice {S O N E U C} (EU : encoding U) (gk : genkill_view S O N E U C) :
    lattice (avail_set EU gk) := finite_must_lattice EU (expr_universe EU gk).

(** Edge generation is added after invalidated expressions are removed. *)
Definition avail_transfer {S O N E U C} (EU : encoding U) (gk : genkill_view S O N E U C)
    (e : E) (a : avail_set EU gk) : avail_set EU gk :=
  finite_clamp EU (expr_universe EU gk)
    (FinSet.union EU
       (FinSet.of_list EU (filter (fun u => negb (kill gk e u)) (FinSet.elements (proj1_sig a))))
       (FinSet.of_list EU (gen gk e))).

(** No expression is already available at an entry. *)
Definition available_system {S O N E U C} (EU : encoding U) (gk : genkill_view S O N E U C) :
    System.t N (dense_constraint N E) (avail_set EU gk) :=
  forward_system (cfg (gkview gk)) (fun _ => finite_clamp EU (expr_universe EU gk) FinSet.empty)
    (avail_transfer EU gk).

(** Anticipation propagates backward and excludes every expression at terminal nodes. *)
Definition busy_system {S O N E U C} (EU : encoding U) (gk : genkill_view S O N E U C) :
    System.t N (dense_constraint N E) (avail_set EU gk) :=
  backward_system (cfg (gkview gk))
    (fun n => match Graph.out (cfg (gkview gk)) n with
              | nil => finite_clamp EU (expr_universe EU gk) FinSet.empty
              | _ => bot (avail_lattice EU gk)
              end)
    (avail_transfer EU gk).

(** A code-motion candidate proposes insertions on edges and deletions at nodes. *)
Record lcm_result (E N U : Type) : Type := LcmResult {
  insert : E -> list U;
  delete : N -> list U
}.

Arguments LcmResult {E N U}.
Arguments insert {E N U}.
Arguments delete {E N U}.

(** Acceptance requires anticipated, currently unavailable insertions and available deletions. *)
Definition lcm_check {S O N E U C} {U1 U2 U3 : list U} (EU : encoding U)
    (gk : genkill_view S O N E U C) (avail : N -> finite_set EU U1) (busy : N -> finite_set EU U2)
    (avail2 : N -> finite_set EU U3) (r : lcm_result E N U) : bool :=
  forallb (fun e => forallb (fun u =>
      fmem EU u (busy (Graph.target (cfg (gkview gk)) e)) &&
      negb (fmem EU u (avail (Graph.source (cfg (gkview gk)) e)))) (insert r e))
    (edges_of (cfg (gkview gk))) &&
  forallb (fun n => forallb (fun u => fmem EU u (avail2 n)) (delete r n))
    (Graph.nodes (cfg (gkview gk))).

(** * Transfer membership *)

Local Lemma avail_clamp_spec {U} (EU : encoding U) us s u :
  fmem EU u (finite_clamp EU us s) = true <-> In u us /\ FinSet.mem EU u s = true.
Proof.
  change (FinSet.mem EU u (FinSet.of_list EU (filter (fun x => FinSet.mem EU x s) us)) = true
    <-> In u us /\ FinSet.mem EU u s = true).
  rewrite FinSet.of_list_spec, filter_In; reflexivity.
Qed.

Local Lemma avail_transfer_spec {S O N E U C} (EU : encoding U)
    (gk : genkill_view S O N E U C) e a u :
  fmem EU u (avail_transfer EU gk e a) = true ->
  (fmem EU u a = true /\ kill gk e u = false) \/ In u (gen gk e).
Proof.
  unfold avail_transfer; rewrite avail_clamp_spec, FinSet.mem_union, !FinSet.of_list_spec,
    filter_In, (FinSet.elements_spec _ _ _ (proj1 (proj2_sig a))), Bool.negb_true_iff.
  tauto.
Qed.

(** * Availability over histories *)

Local Definition available_history {S O N E U C} (m : semantics S O)
    (gk : genkill_view S O N E U C) (s0 : S) (es : list E) (s : S) (u : U) : Prop :=
  exists es1 s1 e es2, es = es1 ++ e :: es2 /\ run_edges m (gkview gk) s0 es1 s1 /\
    run_edges m (gkview gk) s1 (e :: es2) s /\ In u (gen gk e) /\ uval gk s u = uval gk s1 u.

Local Lemma available_history_step {S O N E U C} (m : semantics S O) (en : endings S)
    (gk : genkill_view S O N E U C) s0 es s l s' e u :
  genkill_laws m en gk -> reachable_state m s -> step m s l s' ->
  taken (gkview gk) s l s' e -> run_edges m (gkview gk) s0 es s ->
  ((available_history m gk s0 es s u /\ kill gk e u = false) \/ In u (gen gk e)) ->
  available_history m gk s0 (es ++ [e]) s' u.
Proof.
  intros Hgk Hs Hstep Htaken Hrun [[Hhistory Hkill]|Hgen].
  - destruct Hhistory as [pre [s1 [d [post [Hes [Hpre [Hpost [Hgen Hvalue]]]]]]]].
    exists pre, s1, d, (post ++ [e]); split.
    + rewrite Hes, <- app_assoc; reflexivity.
    + split; [exact Hpre|]; split.
      * replace (d :: post ++ [e]) with ((d :: post) ++ [e]) by reflexivity.
        eapply run_edges_app; [exact Hpost|]; econstructor;
          [exact Hstep|exact Htaken|constructor].
      * split; [exact Hgen|rewrite (kill_frame Hgk s l s' e u Hs Hstep Htaken Hkill), Hvalue;
          reflexivity].
  - exists es, s, e, []; split; [reflexivity|]; split; [exact Hrun|]; split.
    + econstructor; [exact Hstep|exact Htaken|constructor].
    + split; [exact Hgen|exact (gen_value Hgk s l s' e u Hs Hstep Htaken Hgen)].
Qed.

(** Each available expression was computed in the run prefix with its current value. *)
Theorem available_sound {S O N E U C} (m : semantics S O) (en : endings S) (EU : encoding U)
    (gk : genkill_view S O N E U C) (sigma : N -> avail_set EU gk) :
  genkill_laws m en gk ->
  post_solution (avail_lattice EU gk) (available_system EU gk) sigma ->
  forall s0 es s u, initial m s0 -> run_edges m (gkview gk) s0 es s ->
    fmem EU u (sigma (point (gkview gk) s)) = true ->
    exists es1 s1 e es2, es = es1 ++ e :: es2 /\ run_edges m (gkview gk) s0 es1 s1 /\
      run_edges m (gkview gk) s1 (e :: es2) s /\ In u (gen gk e) /\ uval gk s u = uval gk s1 u.
Proof.
  intros Hgk Hpost s0 es s u Hs0 Hrun Hu.
  destruct (proj1 (forward_post_solution_iff _ _ _ _ _) Hpost) as [Hseed Hflow].
  assert (Hextend : forall mid fs t, run_edges m (gkview gk) mid fs t -> forall pre,
    run_edges m (gkview gk) s0 pre mid ->
    (forall v, fmem EU v (sigma (point (gkview gk) mid)) = true ->
      available_history m gk s0 pre mid v) ->
    forall v, fmem EU v (sigma (point (gkview gk) t)) = true ->
      available_history m gk s0 (pre ++ fs) t v).
  { intros mid fs t Hsuffix; induction Hsuffix as
      [mid|mid l mid' e fs t Hstep Htaken Hsuffix IH|
       mid l mid' fs t Hstep Hstay Hsuffix IH]; intros pre Hpre Hfact v Hv.
    - rewrite app_nil_r; exact (Hfact v Hv).
    - assert (Hmid : reachable_state m mid) by (eapply history_reachable; eassumption).
      destruct (view_taken_edge m (gkview gk) mid l mid' e (gk_view Hgk)
        Hmid Hstep Htaken) as [He [Hsource Htarget]].
      replace (pre ++ e :: fs) with ((pre ++ [e]) ++ fs) by
        (rewrite <- app_assoc; reflexivity).
      apply IH; [| |exact Hv].
      + eapply run_edges_app; [exact Hpre|]; econstructor;
          [exact Hstep|exact Htaken|constructor].
      + intros w Hw; assert (Htransfer :
          fmem EU w (avail_transfer EU gk e (sigma (point (gkview gk) mid))) = true).
        { rewrite <- Hsource; apply (set_member_subset EU _ _ (Hflow e He)).
          now rewrite Htarget. }
        apply avail_transfer_spec in Htransfer; eapply available_history_step;
          [exact Hgk|exact Hmid|exact Hstep|exact Htaken|exact Hpre|].
        destruct Htransfer as [[Hw' Hkill]|Hgen].
        * left; split; [apply Hfact; exact Hw'|exact Hkill].
        * now right.
    - exfalso; exact (gk_no_stays Hgk mid l mid' Hstay). }
  apply (Hextend s0 es s Hrun []); [constructor| |exact Hu].
  - intros v Hv; pose proof (Hseed _ (entry_points (gk_view Hgk) s0 Hs0)) as Hbound.
    pose proof (set_member_subset EU _ _ Hbound v Hv) as Hempty.
    apply avail_clamp_spec in Hempty; destruct Hempty as [_ Hempty].
    rewrite FinSet.mem_empty in Hempty; discriminate.
Qed.

(** * Anticipation on terminating histories *)

(** Every terminating run computes a busy expression before any invalidating edge. *)
Theorem busy_sound {S O N E U C} (m : semantics S O) (en : endings S) (EU : encoding U)
    (gk : genkill_view S O N E U C) (sigma : N -> avail_set EU gk) :
  genkill_laws m en gk ->
  post_solution (avail_lattice EU gk) (busy_system EU gk) sigma ->
  forall s es t u, reachable_state m s -> run_edges m (gkview gk) s es t -> final en t ->
    fmem EU u (sigma (point (gkview gk) s)) = true ->
    exists es1 e es2, es = es1 ++ e :: es2 /\ In u (gen gk e) /\
      forall e', In e' es1 -> kill gk e' u = false.
Proof.
  intros Hgk Hpost s es t u Hs Hrun.
  destruct (proj1 (backward_post_solution_iff _ _ _ _ _) Hpost) as [Hseed Hflow].
  revert Hs; induction Hrun as
    [s|s l s' e es t Hstep Htaken Hrun IH|s l s' es t Hstep Hstay Hrun IH];
    intros Hs Hfinal Hu.
  - pose proof (Hseed _ (view_point_in_nodes m (gkview gk) s (gk_view Hgk) Hs)) as Hbound.
    rewrite (final_exit Hgk s Hs Hfinal) in Hbound.
    pose proof (set_member_subset EU _ _ Hbound u Hu) as Hempty.
    apply avail_clamp_spec in Hempty; destruct Hempty as [_ Hempty].
    rewrite FinSet.mem_empty in Hempty; discriminate.
  - destruct (view_taken_edge m (gkview gk) s l s' e (gk_view Hgk) Hs Hstep Htaken)
      as [He [Hsource Htarget]].
    assert (Htransfer :
      fmem EU u (avail_transfer EU gk e (sigma (point (gkview gk) s'))) = true).
    { rewrite <- Htarget; apply (set_member_subset EU _ _ (Hflow e He)); now rewrite Hsource. }
    apply avail_transfer_spec in Htransfer; destruct Htransfer as [[Hnext Hkill]|Hgen].
    + destruct (IH (reachable_state_step m s l s' Hs Hstep) Hfinal Hnext)
        as [pre [d [post [Hes [Hgen Hkills]]]]].
      exists (e :: pre), d, post; split; [cbn; now rewrite Hes|]; split; [exact Hgen|].
      intros d' [<-|Hd']; [exact Hkill|now apply Hkills].
    + exists [], e, es; split; [reflexivity|]; split; [exact Hgen|].
      intros d Hd; contradiction.
  - exfalso; exact (gk_no_stays Hgk s l s' Hstay).
Qed.

(** * Checked lazy code motion *)

(** An accepted insertion is followed by a computation before any kill on every final run. *)
Theorem lcm_insert_safe {S O N E U C} {U1 U2 U3 : list U} (m : semantics S O) (en : endings S)
    (EU : encoding U) (gk : genkill_view S O N E U C) (avail : N -> finite_set EU U1)
    (avail2 : N -> finite_set EU U3) (busy : N -> avail_set EU gk) (r : lcm_result E N U) :
  genkill_laws m en gk ->
  post_solution (avail_lattice EU gk) (busy_system EU gk) busy ->
  lcm_check EU gk avail busy avail2 r = true ->
  forall e u s es t, In e (edges_of (cfg (gkview gk))) -> In u (insert r e) ->
    reachable_state m s -> point (gkview gk) s = Graph.target (cfg (gkview gk)) e ->
    run_edges m (gkview gk) s es t -> final en t ->
    exists es1 e' es2, es = es1 ++ e' :: es2 /\ In u (gen gk e') /\
      forall e'', In e'' es1 -> kill gk e'' u = false.
Proof.
  intros Hgk Hpost Hcheck e u s es t He Hu Hs Hpoint Hrun Hfinal.
  unfold lcm_check in Hcheck; apply andb_true_iff in Hcheck; destruct Hcheck as [Hinsert Hdelete].
  apply forallb_forall with (x := e) in Hinsert; [|exact He].
  apply forallb_forall with (x := u) in Hinsert; [|exact Hu].
  apply andb_true_iff in Hinsert; destruct Hinsert as [Hbusy Hunavailable].
  eapply (busy_sound m en EU gk busy Hgk Hpost s es t u Hs Hrun Hfinal).
  now rewrite Hpoint.
Qed.

(** Accepted deletions use an earlier computation with the expression's current value. *)
Theorem lcm_delete_current {S O N E U C} {U1 U2 : list U} (m' : semantics S O) (en' : endings S)
    (EU : encoding U) (gk gk' : genkill_view S O N E U C) (avail : N -> finite_set EU U1)
    (busy : N -> finite_set EU U2) (avail2 : N -> avail_set EU gk') (r : lcm_result E N U) :
  genkill_laws m' en' gk' -> (forall e, gen gk' e = gen gk e ++ insert r e) -> kill gk' = kill gk ->
  gkview gk' = gkview gk ->
  post_solution (avail_lattice EU gk') (available_system EU gk') avail2 ->
  lcm_check EU gk avail busy avail2 r = true ->
  forall s0 es s n u, initial m' s0 -> run_edges m' (gkview gk') s0 es s ->
    point (gkview gk') s = n -> In n (Graph.nodes (cfg (gkview gk))) -> In u (delete r n) ->
    exists es1 s1 e es2, es = es1 ++ e :: es2 /\ run_edges m' (gkview gk') s0 es1 s1 /\
      run_edges m' (gkview gk') s1 (e :: es2) s /\ In u (gen gk' e) /\
      uval gk' s u = uval gk' s1 u.
Proof.
  intros Hgk Hgen Hkill Hview Hpost Hcheck s0 es s n u Hs0 Hrun Hpoint Hn Hu.
  unfold lcm_check in Hcheck; apply andb_true_iff in Hcheck; destruct Hcheck as [Hinsert Hdelete].
  apply forallb_forall with (x := n) in Hdelete; [|exact Hn].
  apply forallb_forall with (x := u) in Hdelete; [|exact Hu].
  eapply (available_sound m' en' EU gk' avail2 Hgk Hpost s0 es s u Hs0 Hrun).
  now rewrite Hpoint.
Qed.
